'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const html=read('index.html');
const tutorial=read('tutorial.js');
const css=read('polish.css');
const worker=read('sw.js');
assert.match(html,/<canvas id="c"/,'canvas 2D principal ausente');
assert.match(html,/id="nav-tabs"/,'navegação do lobby ausente');
assert.match(html,/href="\/polish\.css\?v=1"/,'CSS de polimento não foi ligado');
assert.match(html,/src="\/tutorial\.js"\s+defer/,'tutorial não está carregado');
assert.match(html,/const ambientCount=0;/,'partículas ambientais decorativas precisam continuar desligadas');
assert.match(html,/spawnImpactWave\(/,'VFX de impacto não foi integrado');
assert.match(html,/kind==='diamond'/,'faíscas com formas variadas não foram integradas');
for(const value of ['0','1','2'])assert.ok(html.includes('<option value="'+value+'"'),'opção gráfica '+value+' ausente');
assert.match(tutorial,/Mestre Slime/,'guia do tutorial ausente');
assert.match(tutorial,/slimeTutorialSeen_v2/,'chave do tutorial não foi versionada');
assert.match(css,/#run-board/,'estilo do HUD não encontrado');
assert.match(css,/prefers-reduced-motion/,'suporte a movimento reduzido ausente');
assert.match(worker,/slime-ascendant-shell-v56/,'cache do service worker não foi atualizado');
assert.match(worker,/polish\.css/,'CSS novo não foi incluído no cache offline');
const scripts=[...html.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(s=>s.trim());
assert.ok(scripts.length>0,'nenhum script inline encontrado');
scripts.forEach((code,i)=>new vm.Script(code,{filename:'index-inline-'+(i+1)+'.js'}));
new vm.Script(tutorial,{filename:'tutorial.js'});
new vm.Script(worker,{filename:'sw.js'});
console.log('Visual smoke tests passaram: HTML/JS, tutorial, 3 níveis gráficos, VFX, HUD e cache offline.');
