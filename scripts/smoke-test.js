'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const read = (path) => fs.readFileSync(path, 'utf8');
const html = read('index.html');
const server = read('server.js');
const auth = read('auth.js');
const serviceWorker = read('sw.js');
const manifest = JSON.parse(read('manifest.webmanifest'));
const capacitor = JSON.parse(read('android-app/capacitor.config.json'));
const apkWorkflow = read('.github/workflows/build-apk.yml');
const offlinePage = read('android-app/www/offline.html');
const scriptStart = html.indexOf('<script>') + 8;
const scriptEnd = html.lastIndexOf('</script>');
assert.ok(scriptStart >= 8 && scriptEnd > scriptStart, 'script principal ausente');
const app = html.slice(scriptStart, scriptEnd);
new vm.Script(app, { filename: 'index.html' });
for (const [name, source] of Object.entries({ server, auth, serviceWorker })) new vm.Script(source, { filename: name + '.js' });
assert.ok(server.includes('MAX_PLAYERS=4') && server.includes('MAX_CONNECTIONS=40'));
assert.ok(server.includes('function roomForJoin') && server.includes('function isAllowedPlayerName'));
assert.ok(server.includes('client.ping()') && server.includes("ws.on('pong'"));
assert.ok(app.includes("joinOnline(code,$('create-room'))") && app.includes("joinOnline(code,$('priv'))"));
assert.ok(server.includes('if(r.bossIndex<4&&r.t>=BOSS_TICKS[r.bossIndex])'));
assert.ok(server.includes('if(r.t%600===0&&!r.bossActive)'), 'onda não deve avançar durante luta do Boss');
assert.ok(server.includes('r.arena=null;r.activeBossTier=0') && app.includes('r.arena=null;r.activeBossTier=0'));
assert.ok(app.includes('if(S.arena){const arena='), 'cerca do Boss precisa ser desenhada');
assert.ok(server.includes('rerolls:3') && app.includes('rerolls:3'));
assert.ok(server.includes('function rerollSkills(p)') && server.includes("d.t==='reroll'"));
assert.ok(server.includes('else if(p.cr>=10)p.cr-=10'));
assert.ok(app.includes('function offlineReroll()') && app.includes('function rerollSkills()'));
assert.ok(app.includes('id="reroll-skills"'));
const getArray = (source, marker) => {
  const start = source.indexOf(marker);
  const end = source.indexOf('];', start);
  assert.ok(start >= 0 && end > start, marker + ' ausente');
  return vm.runInNewContext(source.slice(start + marker.length, end + 1));
};
const serverXp = getArray(server, 'const ET=').map(enemy => enemy.x);
const offlineXp = getArray(app, 'const OET=').map(enemy => enemy.x);
assert.deepEqual(serverXp, offlineXp, 'XP online e offline precisam ser iguais');
assert.equal(serverXp.length, 8);
assert.ok(auth.includes('slice(0, 15)'));
assert.ok(auth.includes("pathname === '/api/leaderboard'") && app.includes('/api/leaderboard'));
assert.ok(app.includes("player.name||'Slime'"));
assert.ok(manifest.icons.some(icon => icon.src === '/icon.svg'));
assert.ok(apkWorkflow.includes('npm install --no-save sharp'));
assert.ok(apkWorkflow.includes("path.resolve('../icon.svg')") && apkWorkflow.includes('ic_launcher_round.png'));
assert.equal(capacitor.server.errorPath, 'offline.html');
const offlineScript = offlinePage.split('<script>')[1]?.split('</script>')[0];
assert.ok(offlineScript);
new vm.Script(offlineScript, { filename: 'android-app/www/offline.html' });
assert.ok(serviceWorker.includes('slime-ascendant-shell-v34'));
assert.ok(serviceWorker.includes("url.pathname.startsWith('/api/')") && serviceWorker.includes("url.pathname==='/health'"));
console.log('Smoke tests aprovados: HTML/JS, salas, Boss, reroll, XP, ranking e ícone do APK.');
